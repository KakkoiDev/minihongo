window.kaiwaLang = function kaiwaLang() {
  return document.getElementById('kaiwa-app')?.dataset.lang || 'en'
}

window.kaiwaT = function kaiwaT(key, vars) {
  const all = window.KAIWA_I18N
  const lang = window.kaiwaLang()
  const chain = lang === 'mh' ? ['mh', 'ja', 'en'] : [lang, 'en']
  let text = key
  for (const code of chain) {
    const value = all[code]?.[key]
    if (value != null) { text = value; break }
  }
  if (!vars) return text
  return text.replace(/\{(\w+)\}/g, (match, name) => (
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : match
  ))
}
